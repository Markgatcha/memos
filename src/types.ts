/**
 * Filter criteria for searching memories.
 */
export interface SearchFilter {
  /** Full-text search query. */
  query?: string;
  /** Filter by memory type. */
  type?: MemoryType;
  /** Minimum importance threshold [0, 1]. */
  minImportance?: number;
  /** Maximum importance threshold [0, 1]. */
  maxImportance?: number;
  /** Metadata key-value filter. */
  metadata?: Record<string, unknown>;
  /** Limit the number of results. */
  limit?: number;
  /** Offset for pagination. */
  offset?: number;
  /** Sort field. */
  sortBy?:
    | "importance"
    | "createdAt"
    | "updatedAt"
    | "accessCount"
    | "relevance"
    | "trustScore";
  /** Sort direction. */
  sortOrder?: "asc" | "desc";
  /** Filter by tags (AND logic — node must have ALL specified tags). */
  tags?: string[];
  /** Filter by namespace (experimental). */
  namespace?: string;
  /** Filter by provenance source. */
  source?: MemorySource;
  /** Minimum trust score [0, 1]. */
  minTrustScore?: number;
  /**
   * When true (default), exclude memories whose `validTo` is in the
   * past (i.e. historical/superseded memories). Set to false to
   * include historical memories.
   */
  includeHistorical?: boolean;
  /**
   * When set, only return memories that were valid at this point in
   * time (Unix ms). A memory is "valid at time T" if:
   *   (validFrom is null OR validFrom <= T) AND
   *   (validTo is null OR validTo >= T)
   */
  validAt?: number;
}

