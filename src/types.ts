/**
 * A memory node bundled with its relevance score after a search.
 */
export interface ScoredMemory {
  node: MemoryNode;
  /** Relevance score returned by the search algorithm. */
  score: number;
  /**
   * Provenance tier of the result's channel (see `ProvenanceTier`).
   * Stamped by `decorateTrustFlags` for agent-facing result sets.
   */
  provenance?: ProvenanceTier;
  /**
   * Citable `[mem:hex]` token tracing the memory to its source episode
   * (see `src/citations.ts`). Stamped by `decorateTrustFlags`.
   */
  citation?: string;
  /**
   * True when the memory comes from a low-trust channel (`imported` /
   * `tool-output` tier, or quarantined-then-released): the host agent
   * should confirm it instead of silently injecting it as context.
   * Stamped by `decorateTrustFlags`.
   */
  untrustedSource?: boolean;
  /** Optional score breakdown for hybrid retrieval. `graph` marks a
   * node injected by the graph-expansion leg, `ppr` the normalized
   * personalized-PageRank score from the PPR-lite expansion blend,
   * `session` one pulled in
   * by session-sibling expansion, `rerank` the cross-encoder score
   * (squashed to [0,1]) from the two-stage reranking pass, `entity` the
   * query-entity overlap (in [0,1]) that earned the entity-fusion boost,
   * and `entityLeg` the matched-entity count from the entity-inverted-index
   * RRF leg (recall signal, distinct from the `entity` scoring boost),
   * and `provenance` the per-tier trust multiplier from the
   * provenance-trust layer. */
  scores?: {
    keyword?: number;
    semantic?: number;
    hybrid?: number;
    graph?: number;
    ppr?: number;
    session?: number;
    rerank?: number;
    entity?: number;
    /**
     * Present when read-time contradiction resolution demoted this
     * result: the demotion factor applied (see
     * CONTRADICTION_DEMOTION_FACTOR in src/contradictions.ts).
     */
    contradiction_demoted?: number;
    entityLeg?: number;
    /**
     * Present when provenance-trust weighting ran: the per-tier trust
     * multiplier applied (`1 - strength * (1 - tierTrust)` — see
     * `provenanceMultiplier` in src/provenance.ts).
     */
    provenance?: number;
  };
}

/**
 * Lifecycle status of a recorded contradiction pair.
 *
 * - `unresolved`: detected at write time by the rule-based detector;
 *   both versions are kept (add-only). Read-time resolution demotes the
 *   older member. Sleep-time LLM adjudication (future) may resolve it.
 * - `resolved`: a contradiction outcome was confirmed through the
 *   evidence state machine (e.g. an old memory superseded by a new
 *   version) — the pair is recorded for provenance.
 */
export type ContradictionStatus = "unresolved" | "resolved";

/**
 * A recorded contradiction pair: two memory nodes about the same
 * subject that disagree. Node ids are stored in canonical (sorted)
 * order so the UNIQUE(node_a, node_b) constraint dedups pairs
 * regardless of insertion order.
 */
export interface ContradictionRecord {
  id: string;
  nodeA: string;
  nodeB: string;
  detectedAt: number;
  status: ContradictionStatus;
}

