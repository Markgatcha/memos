/**
 * Semantic category for a memory node.
 *
 * - `fact`          — A discrete piece of information.
 * - `preference`    — A user or agent preference.
 * - `context`       — Conversational or situational context.
 * - `relationship`  — An observed relationship between entities.
 * - `entity`        — A named entity (person, place, thing).
 * - `custom`        — Application-defined type.
 */
export type MemoryType =
  "fact" | "preference" | "context" | "relationship" | "entity" | "custom";

/**
 * Provenance source for a memory node.
 *
 * - `user_input`     — Stated directly by the user. Highest trust.
 * - `agent_inferred` — Inferred by an agent from context.
 * - `tool_output`    — Returned by a tool call (treated as untrusted
 *   for agent consumption — see the provenance-trust layer).
 * - `external_data`  — Imported from an external source.
 * - `system`         — Generated by the system itself.
 */
export type MemorySource =
  "user_input" | "agent_inferred" | "tool_output" | "external_data" | "system";

/**
 * Default trust score for each provenance source.
 */
export const DEFAULT_TRUST_SCORES: Record<MemorySource, number> = {
  user_input: 1.0,
  agent_inferred: 0.7,
  tool_output: 0.6,
  external_data: 0.5,
  system: 0.3,
};

/**
 * Provenance tier — the trust channel a memory arrived through, assigned
 * at write time and stored as a column. Ordered highest-trust first:
 *
 * - `user-verified` — explicitly confirmed by the user. Never assigned
 *   automatically — only via an explicit `provenance` option or
 *   `verify()`.
 * - `user`          — ordinary user statements (default for
 *   `source: "user_input"` writes).
 * - `tool-output`   — results returned by tools (`source: "tool_output"`).
 * - `chat`          — model-generated content (`source: "agent_inferred"`
 *   or `"system"`).
 * - `imported`      — bulk imports (`source: "external_data"`).
 *
 * See `src/provenance.ts` for the default rule, trust multipliers, and
 * the read-time trust policy.
 */
export type ProvenanceTier =
  "user-verified" | "user" | "tool-output" | "chat" | "imported";

/**
 * A single unit of memory stored in the graph.
 */
/**
 * Which retrieval pool a memory belongs to — the multi-granularity
 * structure from the LongMemEval-V2 design lessons:
 * - `event`      — raw statements as they were captured (the default; every
 *                  legacy memory reads as `event`).
 * - `note`       — distilled summaries produced by consolidation
 *                  (`summarizeCluster` writes here).
 * - `procedure`  — workflow/procedural knowledge ("how to" steps).
 * Pools are queryable via `SearchFilter.pool` and searched as separate
 * streams by multi-stream context packs.
 */
export type MemoryPool = "event" | "note" | "procedure";

/**
 * Typed multi-scope keys for isolating memories per user, agent, and run.
 * Composed into the underlying namespace string in fixed order
 * (`u:alice/a:coder/r:r1`) — see `src/scope.ts`. Hierarchical by default:
 * querying `{ user: "alice" }` surfaces every memory Alice's agents and
 * runs stored.
 */
export interface MemoryScope {
  /** Owner of the memories (e.g. end-user id). */
  user?: string;
  /** Which agent produced them. */
  agent?: string;
  /** Which session/run produced them. */
  run?: string;
}

export interface MemoryNode {
  /** Globally unique identifier (UUID v4). */
  id: string;
  /** Raw text content of the memory. */
  content: string;
  /** Extractive summary (auto-generated if not supplied). */
  summary: string;
  /** Semantic type of this memory. */
  type: MemoryType;
  /** Arbitrary metadata bag. Must be JSON-serialisable. */
  metadata: Record<string, unknown>;
  /**
   * Base importance score in [0, 1]. Set at write time (default 0.5) or
   * manually via `update`. Lifecycle decisions (eviction, archival)
   * derive an *effective* importance from this base plus recency decay
   * and access reinforcement — see `computeEffectiveImportance` in
   * `src/importance.ts`.
   */
  importance: number;
  /** Creation timestamp (Unix ms). */
  createdAt: number;
  /** Last-modified timestamp (Unix ms). */
  updatedAt: number;
  /** Number of times this node has been retrieved. */
  accessCount: number;
  /** Timestamp of last access (Unix ms). */
  lastAccessed: number;
  /** Custom tags for categorisation. */
  tags: string[];
  /** TTL expiration as Unix timestamp (seconds). null = no expiration. */
  expiresAt: number | null;
  /** Namespace for grouping memories (experimental). */
  namespace: string;
  /**
   * Temporal validity start (Unix ms). When set, the memory is
   * considered "active" from this point in time. null = always valid.
   */
  validFrom: number | null;
  /**
   * Temporal validity end (Unix ms). When set, the memory becomes
   * "historical" (excluded from default search) after this time.
   * null = no expiry. Superseded memories keep their validTo so the
   * history is queryable via `searchTemporal`.
   */
  validTo: number | null;
  /**
   * Where this memory originated. Used for provenance and trust
   * scoring.
   * - `user_input`     — Stated directly by the user. Highest trust.
   * - `agent_inferred` — Inferred by an agent from context. Lower trust.
   * - `external_data`  — Imported from an external source (API, file, etc.).
   * - `system`         — Generated by the system itself.
   */
  source: MemorySource;
  /**
   * Provenance tier — the trust channel this memory arrived through
   * (`user-verified` > `user` > `tool-output` > `chat` > `imported`).
   * Assigned at write time from `CreateMemoryInput.provenance` or the
   * source-derived default (see `resolveProvenance` in
   * `src/provenance.ts`); backfilled as `"user"` for legacy rows.
   */
  provenance: ProvenanceTier;
  /**
   * Write-gate quarantine flag. When the local-heuristic classifier
   * (`screenWrite` in `src/quarantine.ts`) flags instruction-like
   * content, the memory is still stored (add-only) but quarantined:
   * excluded from recall by default until reviewed via
   * `memos quarantine list|release`.
   */
  quarantined: boolean;
  /** Unix ms when the memory was quarantined. null when never. */
  quarantinedAt: number | null;
  /** `;`-joined quarantine signal codes. null when never quarantined. */
  quarantineReason: string | null;
  /**
   * Retrieval pool this memory belongs to (multi-granularity retrieval).
   * Optional for backward compatibility with custom storage adapters;
   * treated as `"event"` when absent.
   */
  pool?: MemoryPool;
  /**
   * Harness that wrote this memory (`"claude-code"`, `"cline"`,
   * `"codex"`, `"gemini-cli"`, `"openclaw"`, or `"unknown"`). Stamped
   * at write time by `store()` via `detectHarness()`; optional for
   * backward compatibility with node literals and custom storage
   * adapters — reads as `"unknown"` when absent. Legacy rows are
   * backfilled as `"unknown"` by the schema migration.
   */
  harness?: string;
  /**
   * Trust score in [0, 1]. Influences retrieval ranking. Starts at
   * 1.0 for `user_input`, 0.7 for `agent_inferred`, 0.5 for
   * `external_data`, 0.3 for `system`. Can be manually adjusted via
   * `memos.setTrust()`.
   */
  trustScore: number;
  /**
   * Dynamic confidence score in [0, 1]. Reflects how sure the system
   * is that this memory is still true, given new observations.
   * - Reinforced when new observations agree (confidence goes up)
   * - Revised when new observations partially conflict (confidence goes down)
   * - Superseded when new facts clearly replace old ones (marked historical)
   * Stored in metadata as `confidence` and `evidenceCount`.
   */
  confidence?: number;
  /** Number of evidence events (reinforces + revisions) that touched this memory. */
  evidenceCount?: number;
}

/**
 * Partial input accepted when creating a new memory.
 * Only `content` is required; everything else has defaults.
 */
export interface CreateMemoryInput {
  content: string;
  type?: MemoryType;
  metadata?: Record<string, unknown>;
  summary?: string;
  importance?: number;
  /** TTL in seconds from now. */
  ttl?: number;
  /** Custom tags. */
  tags?: string[];
  /** Namespace (experimental). */
  namespace?: string;
  /**
   * Typed multi-scope isolation. Composed into the namespace string
   * (fixed order user → agent → run); takes precedence over `namespace`
   * when both are supplied.
   */
  scope?: MemoryScope;
  /** Temporal validity start (Unix ms). null = always valid. */
  validFrom?: number | null;
  /** Temporal validity end (Unix ms). null = no expiry. */
  validTo?: number | null;
  /** Provenance source. Default: `user_input`. */
  source?: MemorySource;
  /**
   * Provenance tier override (`user-verified` > `user` > `tool-output` >
   * `chat` > `imported`). When omitted, the tier is derived from
   * `source` via the default rule (see `resolveProvenance` in
   * `src/provenance.ts`): `user_input` → `user`, `tool_output` →
   * `tool-output`, `agent_inferred`/`system` → `chat`, `external_data` →
   * `imported`. `user-verified` is never assigned automatically.
   */
  provenance?: ProvenanceTier;
  /**
   * Write-gate screening: when true (default), the local-heuristic
   * classifier (`screenWrite`) runs on `content` and flags
   * instruction-like payloads by storing them quarantined (excluded
   * from recall until reviewed). Set to false to bypass screening for
   * trusted bulk operations. No LLM is ever consulted on this path.
   */
  quarantineScreen?: boolean;
  /**
   * Retrieval pool for this memory. Default: `"event"`. Use `"procedure"`
   * for workflow/how-to knowledge — multi-stream context packs search
   * procedures with a dedicated query stream.
   */
  pool?: MemoryPool;
  /**
   * One line of write-time context describing the situation this memory
   * was captured in (e.g. "stated while debugging the deploy pipeline").
   * Stored in `metadata.context`, prepended to the embedded text, and
   * included in context packs. When absent, the optional
   * `MemOSConfig.enrichMemory` hook is consulted.
   */
  context?: string;
  /** Trust score [0, 1]. Overrides the default for the chosen source. */
  trustScore?: number;
  /**
   * Harness attribution override (e.g. `"claude-code"`, `"cline"`).
   * When omitted, `store()` stamps the harness detected from the
   * environment via `detectHarness()` (see `src/harness.ts`).
   */
  harness?: string;
  /**
   * Dynamic confidence score [0, 1] for the confidence state machine.
   * Used to track how sure the system is that this memory is still true.
   * If omitted, defaults to INITIAL_CONFIDENCE (0.5).
   */
  confidence?: number;
  /**
   * Evidence count for the confidence state machine.
   * Number of reinforce/revise events this memory has accumulated.
   * If omitted, defaults to 0 for manually stored items.
   */
  evidenceCount?: number;
  /**
   * When true, apply the Hermes-style retain pre-filter (v1.6.26) before
   * writing: low-signal content (acknowledgements, chit-chat, near-empty
   * text) is skipped so long-term memory isn't flooded with noise that would
   * later bloat context-packs. Default: false (write always).
   */
  filterRetain?: boolean;
  /**
   * When true, run the evidence state machine before writing:
   * content that confirms an existing memory reinforces it (confidence ↑)
   * instead of writing a duplicate node, and content that contradicts it
   * supersedes the old version. Default: false — store() appends a new
   * node every time (use dedupe()/consolidate() for explicit merging).
   */
  evidenceLearning?: boolean;
  /**
   * Reference time (Unix ms) for this write. Overrides `Date.now()` as
   * the write timestamp AND as the reference time for deterministic
   * temporal parsing (event extraction / update resolution). Primarily
   * a testing hook — omit in production so the wall clock is used.
   */
  now?: number;
}

