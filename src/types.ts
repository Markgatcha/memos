/**
 * Backend-agnostic storage contract.
 *
 * Any persistence backend (SQLite, Postgres, Redis, Qdrant …) must
 * implement this interface. The core engine only depends on this
 * contract, never on a concrete backend.
 */
export interface StorageAdapter {
  /** Initialise tables / indices / connections. Called once at startup. */
  init(): Promise<void>;

  /** Persist a new memory node. Returns the created node. */
  saveNode(node: MemoryNode): Promise<MemoryNode>;

  /** Retrieve a node by ID. Returns `null` when not found.
   *  Implementations should bump the access stats (access_count,
   *  last_accessed) on read. For side-effect-free reads, use `peekNode`. */
  getNode(id: string): Promise<MemoryNode | null>;

  /**
   * Side-effect-free variant of `getNode`. Does not increment
   * `access_count` or update `last_accessed`. Use for internal lookups
   * where the read is not a user-initiated retrieval — e.g. tag
   * updates, TTL changes, eviction candidate selection.
   */
  peekNode?(id: string): Promise<MemoryNode | null>;

  /**
   * Delete the single least-important node, where "least important" is
   * defined as lowest `importance` then oldest `last_accessed`.
   * Returns the id of the deleted node, or null if the table is empty.
   * Implementations may fall back to in-memory selection if SQL is
   * not appropriate.
   */
  evictLeastImportant?(): Promise<string | null>;

  /** Partially update a node. Returns the updated node. */
  updateNode(id: string, input: UpdateMemoryInput): Promise<MemoryNode | null>;

  /** Delete a node and all connected edges. */
  deleteNode(id: string): Promise<boolean>;

  /** Persist a new edge. Returns the created edge. */
  saveEdge(edge: MemoryEdge): Promise<MemoryEdge>;

  /**
   * Batch-insert multiple edges in a single transaction.
   * Falls back to individual saveEdge calls when not implemented.
   */
  saveEdgesBatch?(edges: MemoryEdge[]): Promise<MemoryEdge[]>;

  /** Retrieve an edge by ID. */
  getEdge(id: string): Promise<MemoryEdge | null>;

  /** Delete an edge by ID. */
  deleteEdge(id: string): Promise<boolean>;

  /** Query nodes with filters. */
  queryNodes(filter: SearchFilter): Promise<ScoredMemory[]>;

  /** Persist an embedding vector for a node. */
  saveEmbedding?(
    nodeId: string,
    vector: EmbeddingVector,
    model: string,
  ): Promise<void>;

  /** Return stored embedding metadata for startup backfill decisions. */
  getEmbeddingInfo?(nodeId: string): Promise<EmbeddingRecordInfo | null>;

  /** Query nodes by vector similarity. */
  querySimilarEmbeddings?(
    vector: EmbeddingVector,
    filter: SearchFilter,
    limit: number,
    threshold?: number,
  ): Promise<ScoredMemory[]>;

  /** Query edges, optionally filtered by source/target. */
  queryEdges(filter?: {
    sourceId?: string;
    targetId?: string;
    relation?: EdgeRelation;
  }): Promise<MemoryEdge[]>;

  /** Return the full graph (nodes + edges). */
  getGraph(): Promise<GraphSnapshot>;

  /**
   * Return every persisted embedding (node id + vector + model). Used
   * by memory consolidation. Implementations may return an empty
   * array when embeddings are not stored.
   */
  getAllEmbeddings?(): Promise<Array<{ nodeId: string; vector: EmbeddingVector; model: string }>>;

  /**
   * Update only the `namespace` of a node. Used by `archive` to
   * move a memory to the `archived` namespace.
   */
  setNodeNamespace?(id: string, namespace: string): Promise<void>;

  /** Set TTL on a node. */
  setTTL(id: string, seconds: number): Promise<void>;

  /** Clear TTL on a node. */
  clearTTL(id: string): Promise<void>;

  /** Delete expired nodes and return the count of deleted nodes. */
  sweepExpired(): Promise<number>;

  /** Get all nodes with a specific tag. */
  queryNodesByTag(tag: string): Promise<MemoryNode[]>;

  /** Delete all nodes and edges (batch operation). */
  deleteAllNodes(): Promise<void>;

  /** Close connections and release resources. */
  close(): Promise<void>;
}

