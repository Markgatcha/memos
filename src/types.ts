export type EmbeddingVector = number[];

export interface EmbeddingProvider {
  /** Stable provider identifier, e.g. "local-hash" or "ollama". */
  id: string;
  /** Human-readable embedding model name. */
  model: string;
  /** Expected vector dimensionality. */
  dimensions: number;
  /** Generate a normalized embedding vector for a text input. */
  embed(text: string): Promise<EmbeddingVector>;
  /**
   * Optional batch embedding. If the provider can batch, override this to
   * amortize network round-trips. Default implementation calls `embed` for
   * each text in order. The returned vectors must be in the same order as
   * the input `texts` array.
   */
  batchEmbed?(texts: string[]): Promise<EmbeddingVector[]>;
}

export type EmbeddingProviderKind =
  | "local-hash"
  | "ollama"
  | "openai-compatible"
  | "voyage"
  | "cohere"
  | "fastembed";

export interface EmbeddingConfig {
  /** Enables embedding generation. Defaults to true when semantic search is enabled. */
  enabled?: boolean;
  /** Built-in provider kind, or a custom provider implementation. */
  provider?: EmbeddingProviderKind | EmbeddingProvider;
  /** Provider model name. */
  model?: string;
  /** Embedding vector dimensions. */
  dimensions?: number;
  /** Base URL for Ollama or OpenAI-compatible embedding endpoints. */
  baseUrl?: string;
  /** API key for OpenAI-compatible embedding endpoints. */
  apiKey?: string;
}

export interface EmbeddingRecordInfo {
  model: string;
  dimensions: number;
  updatedAt: number;
}

/**
 * Per-node embedding pipeline status. `pending` means the node has been
 * stored but its embedding has not been computed yet. `ready` means the
 * persisted vector is fresh for the current provider/model. `failed`
 * means the most recent attempt gave up after retries.
 */
export type EmbeddingNodeStatus = "pending" | "queued" | "running" | "ready" | "failed";

/** Lightweight status snapshot returned by `memos.embeddingStatus()`. */
export interface EmbeddingNodeStatusInfo {
  nodeId: string;
  status: EmbeddingNodeStatus;
  attempts: number;
  lastError: string | null;
  updatedAt: number;
}

/** Aggregate status returned by `memos.embeddingStatus()` (no args). */
export interface EmbeddingQueueStatus {
  pending: number;
  running: number;
  total: number;
  nodes: EmbeddingNodeStatusInfo[];
}

/**
 * Configuration for the background embedding queue. All fields are
 * optional; sensible defaults are used when omitted.
 */
export interface EmbeddingQueueConfig {
  /** Max concurrent in-flight embed calls. Default 2. */
  concurrency?: number;
  /** Max buffered jobs before `enqueue` throws. Default 10000. */
  maxQueueSize?: number;
  /** Max retry attempts per job before marking it failed. Default 3. */
  maxRetries?: number;
  /** Base backoff in ms; retries use exponential backoff. Default 250. */
  retryBackoffMs?: number;
  /**
   * If true, `store()` waits for the embedding to complete before
   * returning. Default false — background mode. Tests and the CLI
   * `memos flush-embeddings` command benefit from this being false.
   */
  synchronous?: boolean;
}

