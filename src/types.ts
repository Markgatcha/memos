/**
 * Detailed diagnostics snapshot returned by `memos.diagnostics()`.
 */
export interface DiagnosticsResult {
  /** Total number of stored memories. */
  totalNodes: number;
  /** Total number of edges. */
  totalEdges: number;
  /** Number of memories with embeddings. */
  nodesWithEmbeddings: number;
  /** Number of memories with temporal validity set. */
  nodesWithValidity: number;
  /** Number of historical (superseded) memories. */
  historicalNodes: number;
  /** Number of memories with a TTL. */
  nodesWithTTL: number;
  /** Number of expired memories pending sweep. */
  expiredNodes: number;
  /** Average importance across all nodes. */
  avgImportance: number;
  /** Average trust score across all nodes. */
  avgTrustScore: number;
  /** Breakdown of nodes by provenance source. */
  bySource: Record<string, number>;
  /** Breakdown of nodes by memory type. */
  byType: Record<string, number>;
  /** Breakdown of nodes by namespace. */
  byNamespace: Record<string, number>;
  /** Database file size in bytes. */
  dbSizeBytes: number;
  /** Embedding queue status, if configured. */
  embeddingQueue?: EmbeddingQueueStatus;
  /** Whether the storage adapter supports optional methods. */
  storageCapabilities: {
    peekNode: boolean;
    evictLeastImportant: boolean;
    saveEmbedding: boolean;
    getAllEmbeddings: boolean;
    setNodeNamespace: boolean;
  };
}
