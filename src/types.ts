/**
 * Backend-agnostic storage contract.
 *
 * Any persistence backend (SQLite, Postgres, Redis, Qdrant …) must
 * implement this interface. The core engine only depends on this
 * contract, never on a concrete backend.
 */
export interface StorageAdapter {
  /** Initialise tables / indices / connections. Called once at startup. */
  init(): Promise<void>;

  /** Persist a new memory node. Returns the created node. */
  saveNode(node: MemoryNode): Promise<MemoryNode>;

  /** Retrieve a node by ID. Returns `null` when not found.
   *  Implementations should bump the access stats (access_count,
   *  last_accessed) on read. For side-effect-free reads, use `peekNode`. */
  getNode(id: string): Promise<MemoryNode | null>;

  /**
   * Side-effect-free variant of `getNode`. Does not increment
   * `access_count` or update `last_accessed`. Use for internal lookups
   * where the read is not a user-initiated retrieval — e.g. tag
   * updates, TTL changes, eviction candidate selection.
   */
  peekNode?(id: string): Promise<MemoryNode | null>;

  /**
   * Delete the single least-important node, where "least important" is
   * defined as lowest `importance` then oldest `last_accessed`.
   * Returns the id of the deleted node, or null if the table is empty.
   * Implementations may fall back to in-memory selection if SQL is
   * not appropriate.
   */
  evictLeastImportant?(): Promise<string | null>;

  /** Partially update a node. Returns the updated node. */
  updateNode(id: string, input: UpdateMemoryInput): Promise<MemoryNode | null>;

  /** Delete a node and all connected edges. */
  deleteNode(id: string): Promise<boolean>;

  /** Persist a new edge. Returns the created edge. */
  saveEdge(edge: MemoryEdge): Promise<MemoryEdge>;

  /**
   * Batch-insert multiple edges in a single transaction.
   * Falls back to individual saveEdge calls when not implemented.
   */
  saveEdgesBatch?(edges: MemoryEdge[]): Promise<MemoryEdge[]>;

  /** Retrieve an edge by ID. */
  getEdge(id: string): Promise<MemoryEdge | null>;

  /** Delete an edge by ID. */
  deleteEdge(id: string): Promise<boolean>;

  /**
   * Close (invalidate) the currently-valid edges incident to a node by
   * stamping `valid_to = validTo`. Rows are updated, never deleted, so
   * as-of reads at earlier timestamps still return them.
   * Returns the number of edges closed.
   */
  closeEdgesForNode?(nodeId: string, validTo: number): Promise<number>;

  /** Query nodes with filters. */
  queryNodes(filter: SearchFilter): Promise<ScoredMemory[]>;

  /**
   * Per-harness memory counts (`SELECT harness, COUNT(*) … GROUP BY
   * harness`). Optional — `MemOS.getHarnessCounts()` falls back to a
   * paged `queryNodes` scan when the adapter does not implement it.
   */
  getHarnessCounts?(): Promise<HarnessCount[]>;

  /** Persist an embedding vector for a node. */
  saveEmbedding?(
    nodeId: string,
    vector: EmbeddingVector,
    model: string,
  ): Promise<void>;

  /** Return stored embedding metadata for startup backfill decisions. */
  getEmbeddingInfo?(nodeId: string): Promise<EmbeddingRecordInfo | null>;

  /**
   * Return stored embedding metadata for every node in one round trip.
   * Optional bulk counterpart to `getEmbeddingInfo` — lets startup
   * backfill avoid one SELECT per node. Storages that don't implement it
   * fall back to per-node `getEmbeddingInfo` calls.
   */
  getAllEmbeddingInfos?(): Promise<
    Array<{ nodeId: string } & EmbeddingRecordInfo>
  >;

  /** Query nodes by vector similarity. */
  querySimilarEmbeddings?(
    vector: EmbeddingVector,
    filter: SearchFilter,
    limit: number,
    threshold?: number,
    /**
     * When provided, only rows stored by this exact model are compared.
     * Cosine similarity is meaningless across models, and two different
     * models can share a dimensionality — dimension equality alone does
     * not prevent silently mixing incompatible vectors.
     */
    model?: string,
  ): Promise<ScoredMemory[]>;

  /** Counts of stored embeddings grouped by model (reindex/audit support). */
  getEmbeddingModelCounts?(): Promise<Array<{ model: string; count: number }>>;

  /**
   * Bulk-fetch stored embedding vectors for the given node ids.
   * Used by write-time contradiction detection to avoid one SELECT per
   * neighbor. Returns only ids that have a stored vector.
   */
  getEmbeddingVectors?(
    nodeIds: string[],
  ): Promise<Map<string, EmbeddingVector>>;

  /** Delete all embedding rows stored by the given model. Returns the count. */
  deleteEmbeddingsByModel?(model: string): Promise<number>;

  /** Query edges, optionally filtered by source/target. */
  queryEdges(filter?: {
    sourceId?: string;
    targetId?: string;
    relation?: EdgeRelation;
    /**
     * Bitemporal as-of read: when provided, only edges whose event-time
     * validity interval covers this Unix-ms timestamp are returned
     * (NULL bounds are open-ended). Default returns all edges.
     */
    validAt?: number;
  }): Promise<MemoryEdge[]>;

  /**
   * Record a contradiction pair between two memory nodes. Node ids are
   * canonicalized (sorted) by the implementation so the UNIQUE constraint
   * dedups reversed pairs. Insert is idempotent (no-op when the pair is
   * already recorded).
   */
  addContradiction?(
    nodeA: string,
    nodeB: string,
    status?: ContradictionStatus,
  ): Promise<ContradictionRecord>;

  /**
   * Return recorded contradiction pairs where node_a OR node_b is in
   * `nodeIds` — the bounded read-time lookup for
   * `resolveContradictionsAtRead`.
   */
  getContradictionPairsFor?(nodeIds: string[]): Promise<ContradictionRecord[]>;

  /** Transition a contradiction record between `unresolved`/`resolved`. */
  updateContradictionStatus?(
    id: string,
    status: ContradictionStatus,
  ): Promise<void>;

  /**
   * Procedural lessons (optional — only SQLiteStorage implements these
   * today). `updateProceduralLesson` applies a partial patch (score,
   * counts, timestamps) and returns the updated record, or null when
   * the id is unknown.
   */
  saveProceduralLesson?(lesson: NewProceduralLesson): Promise<ProceduralLesson>;
  getProceduralLesson?(id: string): Promise<ProceduralLesson | null>;
  updateProceduralLesson?(
    id: string,
    patch: Partial<ProceduralLesson>,
  ): Promise<ProceduralLesson | null>;
  listProceduralLessons?(namespace?: string): Promise<ProceduralLesson[]>;

  /**
   * Find memory nodes whose id (dashes ignored) starts with `prefix`
   * (hex, case-insensitive). Backs citation resolution; capped by the
   * implementation to a bounded candidate list.
   */
  findNodesByIdPrefix?(prefix: string): Promise<MemoryNode[]>;

  /** Return the full graph (nodes + edges). */
  getGraph(): Promise<GraphSnapshot>;

  /**
   * Return the graph as of a bitemporal timestamp (unix ms): nodes and
   * edges whose validity interval covers `atTime`. Optional so
   * third-party adapters are not forced to implement history; callers
   * should fall back to filtering `getGraph()` with the same predicates.
   */
  getGraphAtTime?(atTime: number): Promise<GraphSnapshot>;

  /**
   * Return every persisted embedding (node id + vector + model). Used
   * by memory consolidation. Implementations may return an empty
   * array when embeddings are not stored.
   */
  getAllEmbeddings?(): Promise<
    Array<{ nodeId: string; vector: EmbeddingVector; model: string }>
  >;

  /**
   * Update only the `namespace` of a node. Used by `archive` to
   * move a memory to the `archived` namespace.
   */
  setNodeNamespace?(id: string, namespace: string): Promise<void>;

  /** Set TTL on a node. */
  setTTL(id: string, seconds: number): Promise<void>;

  /** Clear TTL on a node. */
  clearTTL(id: string): Promise<void>;

  /** Delete expired nodes and return the count of deleted nodes. */
  sweepExpired(): Promise<number>;

  /** Get all nodes with a specific tag. */
  queryNodesByTag(tag: string): Promise<MemoryNode[]>;

  /**
   * ── item2: entity leg ── candidate generation for hybrid search: node
   * ids whose indexed entities intersect `entities`, ranked by number of
   * matched entities (desc), node id tiebreak. Backed by the
   * `entity_index` inverted table in the SQLite storage. Optional —
   * storages without an entity index omit this and the entity RRF leg
   * degrades to no candidates.
   */
  searchByEntities?(
    entities: string[],
    limit: number,
  ): Promise<Array<{ nodeId: string; matches: number }>>;

  /** Delete all nodes and edges (batch operation). */
  deleteAllNodes(): Promise<void>;

  /** Close connections and release resources. */
  close(): Promise<void>;
}

