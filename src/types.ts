/**
 * Semantic relation between two memory nodes.
 *
 * - `relates_to`     — General association.
 * - `contradicts`    — The target contradicts the source.
 * - `supports`       — The target supports the source.
 * - `derived_from`   — The source was derived from the target.
 * - `part_of`        — The source is a part of the target.
 * - `custom`         — Application-defined relation.
 */
export type EdgeRelation =
  | "relates_to"
  | "contradicts"
  | "supports"
  | "derived_from"
  | "part_of"
  | "temporal_precedes"
  | "custom";

/**
 * A directed, weighted edge connecting two memory nodes.
 */
export interface MemoryEdge {
  /** Globally unique identifier (UUID v4). */
  id: string;
  /** Source node ID. */
  sourceId: string;
  /** Target node ID. */
  targetId: string;
  /** Semantic relation label. */
  relation: EdgeRelation;
  /** Edge weight in [0, 1]. */
  weight: number;
  /** Arbitrary metadata bag. */
  metadata: Record<string, unknown>;
  /**
   * Transaction/ingest time (Unix ms): when MemOS learned the fact.
   * This is the bitemporal transaction-time axis — it is never renamed
   * or repurposed; event-time validity lives in `validFrom`/`validTo`.
   */
  createdAt: number;
  /**
   * Event-time validity start (Unix ms): when the fact became true in the
   * world. `null`/undefined = open-ended (still true, or unknown).
   */
  validFrom?: number | null;
  /**
   * Event-time validity end (Unix ms): when the fact ceased to be true.
   * `null`/undefined = open-ended (still true). Supersession stamps this
   * instead of deleting the row, preserving add-only history for as-of
   * (time-travel) reads.
   */
  validTo?: number | null;
}

/**
 * Input for creating a new edge.
 */
export interface CreateEdgeInput {
  sourceId: string;
  targetId: string;
  relation?: EdgeRelation;
  weight?: number;
  metadata?: Record<string, unknown>;
  /**
   * Event-time validity start (Unix ms): when the fact became true in the
   * world. `null`/undefined = open-ended.
   */
  validFrom?: number | null;
  /**
   * Event-time validity end (Unix ms): when the fact ceased to be true.
   * `null`/undefined = open-ended.
   */
  validTo?: number | null;
}

