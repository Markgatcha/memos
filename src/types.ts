/**
 * Tunable knobs for the hybrid-search Reciprocal Rank Fusion. Lives in
 * `types.ts` (dependency-free) and is re-exported by `src/retrieval.ts`,
 * where `fuseResults()` consumes it. `MemOSConfig.fusion` forwards these
 * to every hybrid search; unset fields fall back to `retrieval.ts`
 * defaults.
 */
export interface FusionOptions {
  /** RRF constant K. Larger K flattens rank differences. Default 60. */
  rrfK?: number;
  /** Weight of the keyword (FTS5) leg. Default 0.8. */
  keywordWeight?: number;
  /** Weight of the semantic (embedding) leg. Default 0.2. */
  semanticWeight?: number;
  /**
   * Lower bound of the trust multiplier (applied as
   * `trustFloor + trustScore * (1 - trustFloor)`). Default 0.7.
   * Set to 1.0 to disable trust weighting.
   */
  trustFloor?: number;
  /**
   * Strength of the confidence/trust combined multiplier from the
   * evidence state machine. Default 0.35. Set to 0 to disable
   * confidence-aware ranking.
   */
  confidenceWeightStrength?: number;
  /**
   * Recency half-life in ms for the tie-break among near-equal scores.
   * Default 30 days. Set to 0 to disable recency tie-breaking.
   */
  recencyHalfLifeMs?: number;
  /**
   * Reference "now" for recency computations. Defaults to wall-clock;
   * injectable for deterministic tests/benchmarks.
   */
  nowMs?: number;
  /**
   * Entities extracted from the query (populated automatically by
   * `hybridSearch` via `extractQueryEntities`). When non-empty, memories
   * whose tags / `metadata.entities` overlap the query entities receive a
   * post-fusion boost — the third retrieval signal alongside keyword and
   * semantic (see the 2026 fused multi-signal retrieval consensus).
   */
  queryEntities?: string[];
  /**
   * Strength of the entity-overlap boost: `score *= 1 + entityWeight *
   * overlap`. Default 0.15. Set to 0 to disable entity-fused scoring.
   *
   * Distinct from `entityLegWeight`: the overlap boost only re-scores
   * candidates the keyword/semantic legs already retrieved, while the
   * entity leg adds recall (entity-matched memories the other legs
   * missed enter the candidate pool).
   */
  entityWeight?: number;
  /**
   * ── item2: entity leg ── weight of the entity-inverted-index RRF leg
   * (the third retrieval signal alongside keyword and semantic). Applied
   * as `entityLegWeight / (rrfK + rank)` per candidate, so entity-matched
   * memories surface even when FTS and embeddings missed them. Default
   * 0.1 (deliberately below the semantic leg's 0.2 weight — see
   * DEFAULT_ENTITY_LEG_WEIGHT). Set to 0 to disable the leg.
   */
  entityLegWeight?: number;
  /**
   * Strength of the provenance-tier trust multiplier from the
   * provenance-trust layer. Applied as
   * `score *= 1 - strength * (1 - tierTrust)` with per-tier trust from
   * `PROVENANCE_TRUST` (user-verified 1.0 … imported 0.72). Default
   * 0.5 — low-trust content is slightly down-ranked without overriding
   * relevance. Set to 0 to disable trust-weighted recall. Calibrated
   * neutral-or-better on the retrieval eval (scripts/eval-retrieval.ts).
   */
  provenanceWeightStrength?: number;
  /**
   * Single-step PPR-lite graph expansion after fusion (HippoRAG-style,
   * see `src/graph-expansion.ts`). The top `graphExpansionSeeds` fused
   * results seed a personalized PageRank (damping 0.5, `graphExpansionHops`
   * hops) over graph edges plus shared-entity links; the final score
   * blends as `(1 - graphExpansionAlpha) * fused + graphExpansionAlpha *
   * pprNorm` with PPR scores normalized to [0,1]. Graph neighbours of
   * seeds that neither retrieval leg surfaced can enter the results this
   * way — the multi-hop recall win without iterative LLM retrieval.
   * Default: false (opt-in; expansion is off unless enabled here or per
   * query via `SearchFilter.graphExpansion: true`). When disabled the
   * pipeline is byte-identical to pre-expansion behaviour (no extra
   * storage reads, no score changes).
   */
  graphExpansion?: boolean;
  /**
   * Blend weight of the normalized PPR score in the post-fusion blend.
   * Default 0.2.
   */
  graphExpansionAlpha?: number;
  /** PPR neighbourhood depth explored from each seed. Default 2. */
  graphExpansionHops?: number;
  /** How many top fused results seed the PPR walk. Default 10. */
  graphExpansionSeeds?: number;
}

/**
 * Configuration options for a MemOS instance.
 */
export interface MemOSConfig {
  /**
   * Optional write-time contextual enrichment hook (contextual retrieval,
   * Anthropic-style). Called once per `store()` with the memory's signals;
   * return a single line describing the situation the memory was captured
   * in (e.g. "stated while debugging the deploy pipeline"). The line is
   * stored in `metadata.context`, prepended to the embedded text, and
   * surfaced in context packs — it makes embeddings carry situational
   * meaning, which is the best-attested cheap retrieval upgrade in the
   * literature. Wire this to a local LLM (0.6B-class is enough) or any
   * heuristic. Errors are swallowed (fail-soft) and `opts.context`
   * always takes precedence over the hook.
   */
  enrichMemory?: (input: {
    content: string;
    type: MemoryType;
    tags: string[];
    source: MemorySource;
    namespace: string;
  }) => Promise<string | null | undefined> | string | null | undefined;
  /**
   * Deployment-specific entity aliases for fused retrieval scoring,
   * merged over the built-in table (`BUILTIN_ENTITY_ALIASES` in
   * `src/entity-extraction.ts`). Keys and values are matched
   * case-insensitively. Use this to canonicalize domain vocabulary —
   * e.g. `{ "sso": "auth", "okta": "auth" }` — so memories surface no
   * matter which phrasing a query uses.
   */
  entityAliases?: Record<string, string>;
  /**
   * Optional LLM distillation hook for `summarizeCluster` /
   * `consolidate`. Receives the contents of one cluster and returns an
   * abstractive summary (a runbook-style note — the highest-value
   * granularity in the LongMemEval-V2 ablations). When omitted or when
   * the hook fails/returns empty, the extractive summarizer is used.
   * Wire this to a local 0.6B–4B model for fully-offline consolidation.
   */
  summarizeClusterLlm?: (input: {
    contents: string[];
    sourceIds: string[];
  }) => Promise<string | null | undefined> | string | null | undefined;
  /**
   * Hybrid-search fusion tuning forwarded to `fuseResults()` on every
   * hybrid search. Unset fields use `src/retrieval.ts` defaults
   * (keyword 0.8 / semantic 0.2 / K 60 — tuned for the hash baseline;
   * stronger embedding models generally want a higher semantic weight).
   */
  fusion?: FusionOptions;

  /**
   * Path to the SQLite database file.
   * @default "~/.memos/memos.db"
   */
  dbPath?: string;

  /**
   * Enable WAL mode for SQLite.
   * @default true
   */
  wal?: boolean;

  /**
   * Maximum number of memories to keep before LRU eviction.
   * Set to `0` to disable eviction.
   * @default 0
   */
  maxMemories?: number;

  /**
   * Auto-link threshold: minimum cosine-similarity score (bag-of-words)
   * between two nodes to automatically create an edge.
   * Set to `0` to disable auto-linking.
   * @default 0.3
   */
  autoLinkThreshold?: number;

  /**
   * Custom storage adapter. When provided, `dbPath` is ignored.
   */
  storage?: StorageAdapter;

  /**
   * Options forwarded to the built-in SQLite storage adapter when
   * `storage` is not supplied. `vectorCacheEntries` bounds the in-process
   * parsed-vector cache (default 25,000 ≈ 100MB at 1024 dims); lower it
   * for memory-constrained hosts.
   */
  storageOptions?: { vectorCacheEntries?: number };
  /**
   * Encryption key for at-rest encryption of the SQLite database.
   * Requires the optional `better-sqlite3-multiple-ciphers` driver
   * (`npm i better-sqlite3-multiple-ciphers`). Falls back to the
   * `MEMOS_KEY` environment variable. Only NEW databases get encrypted —
   * convert an existing plaintext DB with `memos encrypt`.
   */
  cipherKey?: string;

  /**
   * Interval in seconds for the TTL expiration sweep.
   * Set to `0` to disable the sweep.
   * @default 60
   */
  sweepInterval?: number;

  /**
   * Experimental feature flags.
   */
  experimental?: ExperimentalConfig;

  /**
   * Effective importance model tuning. Controls how recency decay and
   * access reinforcement modulate the base `importance` for eviction
   * and archival decisions. See `ImportanceConfig` in `src/importance.ts`.
   */
  importance?: ImportanceConfig;

  /**
   * Half-life (days) for the optional recency boost in hybrid search
   * ranking. Only used when `experimental.recencyBoost` is enabled.
   * @default 14
   */
  recencyHalfLifeDays?: number;

  /**
   * Embedding provider configuration for semantic and hybrid retrieval.
   */
  embeddings?: EmbeddingConfig;

  /**
   * Background embedding queue tuning. Only takes effect when an
   * embedding provider is configured. See `EmbeddingQueueConfig`.
   */
  embeddingQueue?: EmbeddingQueueConfig;
}

