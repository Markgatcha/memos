/**
 * Semantic category for a memory node.
 *
 * - `fact`          — A discrete piece of information.
 * - `preference`    — A user or agent preference.
 * - `context`       — Conversational or situational context.
 * - `relationship`  — An observed relationship between entities.
 * - `entity`        — A named entity (person, place, thing).
 * - `custom`        — Application-defined type.
 */
export type MemoryType =
  | "fact"
  | "preference"
  | "context"
  | "relationship"
  | "entity"
  | "custom";

/**
 * Provenance source for a memory node.
 *
 * - `user_input`     — Stated directly by the user. Highest trust.
 * - `agent_inferred` — Inferred by an agent from context.
 * - `external_data`  — Imported from an external source.
 * - `system`         — Generated by the system itself.
 */
export type MemorySource =
  | "user_input"
  | "agent_inferred"
  | "external_data"
  | "system";

/**
 * Default trust score for each provenance source.
 */
export const DEFAULT_TRUST_SCORES: Record<MemorySource, number> = {
  user_input: 1.0,
  agent_inferred: 0.7,
  external_data: 0.5,
  system: 0.3,
};

/**
 * A single unit of memory stored in the graph.
 */
export interface MemoryNode {
  /** Globally unique identifier (UUID v4). */
  id: string;
  /** Raw text content of the memory. */
  content: string;
  /** Extractive summary (auto-generated if not supplied). */
  summary: string;
  /** Semantic type of this memory. */
  type: MemoryType;
  /** Arbitrary metadata bag. Must be JSON-serialisable. */
  metadata: Record<string, unknown>;
  /** Importance score in [0, 1]. Auto-computed from access patterns. */
  importance: number;
  /** Creation timestamp (Unix ms). */
  createdAt: number;
  /** Last-modified timestamp (Unix ms). */
  updatedAt: number;
  /** Number of times this node has been retrieved. */
  accessCount: number;
  /** Timestamp of last access (Unix ms). */
  lastAccessed: number;
  /** Custom tags for categorisation. */
  tags: string[];
  /** TTL expiration as Unix timestamp (seconds). null = no expiration. */
  expiresAt: number | null;
  /** Namespace for grouping memories (experimental). */
  namespace: string;
  /**
   * Temporal validity start (Unix ms). When set, the memory is
   * considered "active" from this point in time. null = always valid.
   */
  validFrom: number | null;
  /**
   * Temporal validity end (Unix ms). When set, the memory becomes
   * "historical" (excluded from default search) after this time.
   * null = no expiry. Superseded memories keep their validTo so the
   * history is queryable via `searchTemporal`.
   */
  validTo: number | null;
  /**
   * Where this memory originated. Used for provenance and trust
   * scoring.
   * - `user_input`     — Stated directly by the user. Highest trust.
   * - `agent_inferred` — Inferred by an agent from context. Lower trust.
   * - `external_data`  — Imported from an external source (API, file, etc.).
   * - `system`         — Generated by the system itself.
   */
  source: MemorySource;
  /**
   * Trust score in [0, 1]. Influences retrieval ranking. Starts at
   * 1.0 for `user_input`, 0.7 for `agent_inferred`, 0.5 for
   * `external_data`, 0.3 for `system`. Can be manually adjusted via
   * `memos.setTrust()`.
   */
  trustScore: number;
}

/**
 * Partial input accepted when creating a new memory.
 * Only `content` is required; everything else has defaults.
 */
export interface CreateMemoryInput {
  content: string;
  type?: MemoryType;
  metadata?: Record<string, unknown>;
  summary?: string;
  importance?: number;
  /** TTL in seconds from now. */
  ttl?: number;
  /** Custom tags. */
  tags?: string[];
  /** Namespace (experimental). */
  namespace?: string;
  /** Temporal validity start (Unix ms). null = always valid. */
  validFrom?: number | null;
  /** Temporal validity end (Unix ms). null = no expiry. */
  validTo?: number | null;
  /** Provenance source. Default: `user_input`. */
  source?: MemorySource;
  /** Trust score [0, 1]. Overrides the default for the chosen source. */
  trustScore?: number;
  /**
   * When true, apply the Hermes-style retain pre-filter (v1.6.26) before
   * writing: low-signal content (acknowledgements, chit-chat, near-empty
   * text) is skipped so long-term memory isn't flooded with noise that would
   * later bloat context-packs. Default: false (write always).
   */
  filterRetain?: boolean;
}

/**
 * Partial update for an existing memory node.
 */
export interface UpdateMemoryInput {
  content?: string;
  summary?: string;
  type?: MemoryType;
  metadata?: Record<string, unknown>;
  importance?: number;
  tags?: string[];
  namespace?: string;
  /** Temporal validity start (Unix ms). */
  validFrom?: number | null;
  /** Temporal validity end (Unix ms). */
  validTo?: number | null;
  /** Provenance source. */
  source?: MemorySource;
  /** Trust score [0, 1]. */
  trustScore?: number;
}

