#!/usr/bin/env node
/**
 * Documentation coverage audit.
 *
 * Maps the three public surfaces — CLI commands, MCP tools, HTTP routes — to
 * mentions in the docs corpus, so "undocumented" is a list rather than a
 * feeling. Writes docs/coverage.md.
 */

import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function read(relative) {
  return readFileSync(resolve(root, relative), "utf8");
}

function walk(relative, out = []) {
  const absolute = resolve(root, relative);
  for (const entry of readdirSync(absolute)) {
    if (entry === "node_modules" || entry.startsWith(".")) continue;
    const path = join(relative, entry);
    if (statSync(resolve(root, path)).isDirectory()) walk(path, out);
    else if (path.endsWith(".md")) out.push(path);
  }
  return out;
}

const docFiles = [
  "README.md",
  "llms-install.md",
  ...walk("docs"),
  ...walk("plugin/skills"),
].filter((file, index, all) => all.indexOf(file) === index);

const corpus = docFiles.map((file) => read(file)).join("\n");

// CLI commands: the canonical list lives in cli-help.ts.
const cliSource = read("src/cli-help.ts");
const cliBlock = cliSource.slice(
  cliSource.indexOf("CLI_COMMANDS"),
  cliSource.indexOf("];", cliSource.indexOf("CLI_COMMANDS")),
);
const cliCommands = [...cliBlock.matchAll(/"([a-z][a-z0-9-]*)"/g)].map(
  (match) => match[1],
);

// MCP tools: every registered tool has a `name: "memos_*"` entry.
const mcpSource = read("src/mcp.ts");
const mcpTools = [
  ...new Set(
    [...mcpSource.matchAll(/name: "(memos_[a-z_]+)"/g)].map(
      (match) => match[1],
    ),
  ),
].sort();

// HTTP routes: FastAPI decorators in routes.py, served under /api/mem.
const routesSource = read("memos/server/routes.py");
const routes = [
  ...new Set(
    [...routesSource.matchAll(/@router\.(?:get|post|put|delete|patch)\("([^"]+)"/g)].map(
      (match) => `/api/mem${match[1]}`,
    ),
  ),
].sort();

function documented(term, pattern = term) {
  return corpus.includes(pattern);
}

const cliRows = cliCommands.map((command) => ({
  command,
  documented: documented(command, `memos ${command}`),
}));
const mcpRows = mcpTools.map((tool) => ({
  tool,
  documented: documented(tool),
}));
const routeRows = routes.map((route) => ({
  route,
  documented: documented(route),
}));

function pct(rows, key) {
  const hit = rows.filter((row) => row.documented).length;
  return { hit, total: rows.length, pct: Math.round((hit / rows.length) * 100) };
}

const cliStats = pct(cliRows);
const mcpStats = pct(mcpRows);
const routeStats = pct(routeRows);

const table = (header, rows, render) =>
  [
    `| ${header} | Documented |`,
    "| --- | --- |",
    ...rows.map((row) => `| ${render(row)} | ${row.documented ? "yes" : "**no**"} |`),
  ].join("\n");

const markdown = `# Documentation coverage

Generated by \`npm run docs:coverage\`. A mention means the exact identifier
appears somewhere in \`README.md\`, \`llms-install.md\`, \`docs/\`, or
\`plugin/skills/\`. It is a floor, not a quality score: a page can mention a
command without explaining it.

## Summary

| Surface | Documented | Total | Coverage |
| --- | ---: | ---: | ---: |
| CLI commands | ${cliStats.hit} | ${cliStats.total} | ${cliStats.pct}% |
| MCP tools | ${mcpStats.hit} | ${mcpStats.total} | ${mcpStats.pct}% |
| HTTP routes | ${routeStats.hit} | ${routeStats.total} | ${routeStats.pct}% |

## CLI commands

${table("Command", cliRows, (row) => `\`memos ${row.command}\``)}

## MCP tools

${table("Tool", mcpRows, (row) => `\`${row.tool}\``)}

## HTTP routes

${table("Route", routeRows, (row) => `\`${row.route}\``)}

## Undocumented

${[
  ...cliRows
    .filter((row) => !row.documented)
    .map((row) => `- CLI: \`memos ${row.command}\``),
  ...mcpRows
    .filter((row) => !row.documented)
    .map((row) => `- MCP: \`${row.tool}\``),
  ...routeRows
    .filter((row) => !row.documented)
    .map((row) => `- HTTP: \`${row.route}\``),
].join("\n") || "Nothing missing by this check."}
`;

writeFileSync(resolve(root, "docs/coverage.md"), markdown, "utf8");
console.log(
  `docs:coverage CLI ${cliStats.hit}/${cliStats.total} (${cliStats.pct}%) · MCP ${mcpStats.hit}/${mcpStats.total} (${mcpStats.pct}%) · HTTP ${routeStats.hit}/${routeStats.total} (${routeStats.pct}%)`,
);
console.log(`wrote docs/coverage.md (${docFiles.length} docs scanned)`);
